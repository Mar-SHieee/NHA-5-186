"""Summaries expose graph size and cap-related label bias."""

from __future__ import annotations

import math
import statistics
from collections import Counter


def _percentile(values, q):
    return (
        float(sorted(values)[min(len(values) - 1, math.ceil(q * len(values)) - 1)])
        if values
        else 0.0
    )


def size_summary(rows: list[dict]) -> dict:
    ok = [r for r in rows if r.get("status") == "ok"]
    output = {
        "graphs": len(rows),
        "kept": len(ok),
        "dropped": dict(Counter(r.get("status") for r in rows if r.get("status") != "ok")),
    }
    for key in ("n_nodes", "n_edges"):
        vals = [int(r.get(key, 0)) for r in ok]
        output[key] = {
            "mean": statistics.mean(vals) if vals else 0.0,
            "median": statistics.median(vals) if vals else 0.0,
            "p90": _percentile(vals, 0.90),
            "p95": _percentile(vals, 0.95),
            "p99": _percentile(vals, 0.99),
            "max": max(vals, default=0),
        }
    return output


def cap_table(rows: list[dict], caps) -> list[dict]:
    eligible = [r for r in rows if r.get("status") in {"ok", "over_node_cap", "empty_after_filter"}]
    cwe_counts = Counter(cwe for row in eligible for cwe in row.get("cwe", []))
    top_cwes = [cwe for cwe, _ in cwe_counts.most_common(10)]
    output = []
    for cap in caps:
        kept = [
            r
            for r in eligible
            if r.get("status") in {"ok", "over_node_cap"} and r.get("n_nodes", 0) <= cap
        ]
        shares = {
            label: sum(r.get("label") == label for r in kept)
            / max(1, sum(r.get("label") == label for r in eligible))
            for label in (0, 1)
        }
        cwe_shares = {}
        for cwe in top_cwes:
            members = [r for r in eligible if cwe in r.get("cwe", [])]
            cwe_shares[cwe] = sum(
                r.get("status") in {"ok", "over_node_cap"} and r.get("n_nodes", 0) <= cap
                for r in members
            ) / max(1, len(members))
        output.append(
            {
                "cap": cap,
                "share": len(kept) / max(1, len(eligible)),
                "label_0": shares[0],
                "label_1": shares[1],
                "label_gap_pp": abs(shares[1] - shares[0]) * 100,
                "top_cwe_shares": cwe_shares,
            }
        )
    return output


def edge_type_totals(rows: list[dict]) -> dict[str, int]:
    totals = Counter()
    for row in rows:
        if row.get("status") == "ok":
            totals.update(row.get("edge_counts", {}))
    return dict(totals)


def render_report(language: str, config, summaries: dict, cap_rows=None, ablation=None) -> str:
    """Render generated report data without inventing unavailable real-data counts."""
    lines = [
        "# PyG dataset build report",
        "",
        "Generated by `scripts/graphs/build_pyg_dataset.py`.",
        "Cap shares and size distributions apply only to the input rows used for this build; a "
        "sampled or limited manifest is not a corpus-wide estimate.",
        "",
        f"Language: `{language}`",
        f"Configuration: `{config.to_dict()}`",
        "",
    ]
    for split, summary in summaries.items():
        lines.extend(
            [f"## {split}", "", "```json", __import__("json").dumps(summary, indent=2), "```", ""]
        )
    candidates = [
        row for row in (cap_rows or []) if row["share"] >= 0.9 and row["label_gap_pp"] <= 5.0
    ]
    if candidates:
        chosen = min(candidates, key=lambda row: row["cap"])
        lines.extend(
            [
                "",
                f"Smallest cap meeting 90% retention and 5 pp label gap: `{chosen['cap']}` "
                f"({chosen['share']:.1%} retained, {chosen['label_gap_pp']:.2f} pp gap).",
            ]
        )
    if cap_rows:
        lines.extend(
            [
                "## Candidate node caps",
                "",
                "| Cap | Share kept | Label 0 | Label 1 | Gap (pp) |",
                "|---:|---:|---:|---:|---:|",
            ]
        )
        lines.extend(
            f"| {r['cap']} | {r['share']:.3f} | {r['label_0']:.3f} | "
            f"{r['label_1']:.3f} | {r['label_gap_pp']:.2f} |"
            for r in cap_rows
        )
        cwe_caps = {}
        for row in cap_rows:
            for cwe, share in row.get("top_cwe_shares", {}).items():
                cwe_caps.setdefault(cwe, {})[row["cap"]] = share
        if cwe_caps:
            lines.extend(
                [
                    "",
                    "Top CWE share kept:",
                    "",
                    "| CWE | " + " | ".join(str(r["cap"]) for r in cap_rows) + " |",
                    "|---|" + "---:|" * len(cap_rows),
                ]
            )
            lines.extend(
                "| "
                + cwe
                + " | "
                + " | ".join(f"{cwe_caps[cwe].get(r['cap'], 0):.3f}" for r in cap_rows)
                + " |"
                for cwe in cwe_caps
            )
    if ablation:
        lines.extend(
            [
                "",
                "## Rule A/B comparison",
                "",
                "| Rule | Graphs kept | Total nodes | Total edges |",
                "|---|---:|---:|---:|",
                f"| A | {ablation['graphs_a']} | {ablation['nodes_a']} | {ablation['edges_a']} |",
                f"| B | {ablation['graphs_b']} | {ablation['nodes_b']} | {ablation['edges_b']} |",
            ]
        )
    return "\n".join(lines) + "\n"
